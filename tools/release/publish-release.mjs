import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { command, git, api, repo, packages, output, summary, release, state, checkpoint, version, runUrl } from './shared.mjs';

const v = version(JSON.parse(readFileSync('packages/core/package.json', 'utf8')).version);
const mode = process.argv[2];

if (mode === 'open') {
  let existing = release(v, false);
  // A maintenance push with no new version must not announce an old release.
  if (existing && !existing.draft && !existing.assets.some(item => item.name === 'release-state.json')) {
    output('active', false);
    summary(`OpenWA ${v} already has a release. No new package release was requested.`);
    process.exit(0);
  }
  if (!existing) {
    const sha = git('rev-parse', 'HEAD');
    existing = api(`repos/${repo}/releases`, {
      tag_name: `v${v}`, target_commitish: sha, name: `OpenWA ${v}`,
      draft: true, prerelease: v.includes('-'),
      body: `OpenWA ${v} package publication is in progress. Commit-based release notes are generated by the separate Release notes action.`,
    });
  }
  if (!existing.assets.some(item => item.name === 'release-state.json')) {
    const sha = git('rev-parse', 'HEAD');
    const event = process.env.GITHUB_EVENT_PATH ? JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH, 'utf8')) : {};
    const promotionSha = event.after || sha;
    const prs = api(`repos/${repo}/commits/${promotionSha}/pulls`);
    const promotion = prs.find(pr => pr.merged_at && pr.base.ref === 'release' && pr.head.ref === 'master');
    const metadata = promotion?.body?.match(/<!-- openwa-release\s+([\s\S]*?)-->/)?.[1];
    checkpoint(v, {
      sourceSha: sha, packages: packages().map(({ name, version }) => ({ name, version })),
      issue: metadata ? JSON.parse(metadata).issue : undefined,
      skipDiscord: git('show', '-s', '--format=%B', promotionSha).includes('[skip-discord]'),
      publisherRun: runUrl,
    });
  }
  const current = state(v);
  if (current.completedAt) {
    output('active', false);
    summary(`OpenWA ${v} is already complete: ${existing.html_url}`);
    process.exit(0);
  }
  if (current.sourceSha !== git('rev-parse', 'HEAD')) {
    git('checkout', '--detach', current.sourceSha);
    command('pnpm', ['install', '--frozen-lockfile'], { stdio: 'inherit' });
  }
  output('active', true);
  output('upload_npm', !current.npmSubmittedAt);
  output('packages', current.packages.map(pkg => pkg.name));
} else if (mode === 'npm') {
  if (!state(v).npmSubmittedAt) {
    const result = spawnSync('pnpm', ['exec', 'bumpy', 'publish'], { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
    process.stdout.write(result.stdout || '');
    process.stderr.write(result.stderr || '');
    if (result.error) throw result.error;
    const log = `${result.stdout || ''}\n${result.stderr || ''}`.replace(/\x1b\[[0-9;]*m/g, '');
    const codes = [...log.matchAll(/npm (?:error|ERR!) code (\S+)/g)].map(match => match[1]);
    const staged = codes.length > 0 && codes.every(code => code === 'E409') && /previously staged version/i.test(log);
    if (result.status !== 0 && !staged) throw new Error('npm publishing failed; see the package errors above.');
    checkpoint(v, { npmSubmittedAt: new Date().toISOString(), npmValidationPending: staged });
    if (staged) summary('npm already accepted these versions for validation. Tracking availability without uploading them again.');
  }
} else if (mode === 'finish') {
  const current = checkpoint(v, { githubPackagesPublishedAt: new Date().toISOString() });
  const entry = release(v);
  if (entry.draft) {
    api(`repos/${repo}/releases/${entry.id}`, {
      draft: false, body: `${entry.body}\n\n_Package availability and documentation deployment are being tracked separately._\n`,
    }, 'PATCH');
  }
  api(`repos/${repo}/actions/workflows/release-status.yml/dispatches`, { ref: 'master', inputs: { version: v } });
  summary(`## OpenWA ${v} submitted\n\nnpm submission and GitHub Packages publishing finished. The availability action tracks installable packages and documentation, then starts the release notes action.\n\n[Release](https://github.com/${repo}/releases/tag/v${v})\n\n${current.packages.length} package versions are being tracked.`);
} else {
  throw new Error('Use open, npm, or finish.');
}
